# Function to load the images in array numpy
def load_images_from_directory(directory, target_size=(96, 96)):
    images = []
    labels = []
    label_encoder = LabelEncoder()  #codify label of folders

    # Every subfolders (classi) in directory
    class_names = os.listdir(directory)

    #The path exists
    class_names = [name for name in class_names if os.path.isdir(os.path.join(directory, name))]

    # Link every number to each class
    label_encoder.fit(class_names)

    for class_name in class_names:
        class_path = os.path.join(directory, class_name)

        for img_name in os.listdir(class_path):
            img_path = os.path.join(class_path, img_name)

            #Load image, resize it and convert it in a array numpy
            img = Image.open(img_path).resize(target_size)
            img = np.array(img)

            # Add image and label
            images.append(img)
            labels.append(class_name)

    # Convert images e label in array numpy
    images = np.array(images)
    labels = label_encoder.transform(labels)

    return images, labels

