def FK(model,theta):
    # reshape to batch size 1
    t = tf.reshape(theta, shape=(1,2))
    out = model(t)
    # reshape to 1d vector
    out = tf.reshape(out, shape=(2,))
    return out


def FK(model, theta):
    if isinstance(model, tf.keras.Model):
        #For TensorFlow model
        t = tf.reshape(theta, shape=(1, -1))
        out = model(t)
        return tf.reshape(out, shape=(-1,))
    else:
        # Foe Scikit-learn model
        return model.predict(theta.reshape(1, -1)).flatten()



@tf.function
def FK_Jacobian(model,x):
  with tf.GradientTape(persistent=True) as tape:
    tape.watch(x)
    y = FK(model,x)
  return tape.jacobian(y, x)


def FK_Jacobian(model, sample_input, eps=1):
    if isinstance(model, tf.keras.Model):
        # Compute the Jacobian with TensorFlow
        with tf.GradientTape() as tape:
            tape.watch(sample_input)
            y = FK(model, sample_input)
        return tape.jacobian(y, sample_input).numpy()
    else:
        # Compute the Jacobian with Scikit-learn
        sample_input_numpy = sample_input.numpy().flatten()
        def predict_fn(theta):
            return FK(model, np.array(theta))

        return approx_fprime(sample_input_numpy, predict_fn, epsilon=eps)

